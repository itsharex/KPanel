export function diskProblemMessage(code: string): string | undefined {
  return diskProblemMessages[code]
}

export function localizeDiskRuntimeMessage(
  value: string,
  locale: SupportedLocale,
  translate: (source: string) => string,
): string {
  const translated = translate(value)
  if (locale === 'zh-CN' || translated !== value || !/[\u3400-\u9fff]/.test(value)) return translated
  return translate('磁盘任务返回了未识别的状态，请刷新后复核。')
}
